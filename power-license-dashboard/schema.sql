-- ============================================================================

-- 1. Create Master License Inventory Table with Soft-Delete Audit Support
CREATE TABLE IF NOT EXISTS license_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name TEXT NOT NULL,
    vendor_name TEXT NOT NULL,
    category TEXT NOT NULL,
    serial_license_id TEXT NOT NULL,
    vendor_email TEXT NOT NULL,
    start_date DATE NOT NULL,
    renewal_date DATE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,             -- Soft Delete Flag (TRUE = Visible, FALSE = Deactivated)
    deactivated_at TIMESTAMPTZ,                  -- Audit timestamp when item is soft deleted
    deactivated_by TEXT,                         -- Audit user info
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Vendor Directory Table
CREATE TABLE IF NOT EXISTS vendor_directory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name TEXT UNIQUE NOT NULL,
    contact_email TEXT NOT NULL,
    category TEXT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

